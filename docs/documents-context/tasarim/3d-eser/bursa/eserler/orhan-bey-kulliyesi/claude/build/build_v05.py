def kasnak_sacak(g, c, kw, zk):
    """v04: sekizgen kasnağın üstünde dışa taşan tuğla saçak halkası (içi boş; kasnak kapağıyla aynı düzlemde yüz yok)."""
    d, h = P["D_kasnak_sacak_d"], P["D_kasnak_sacak_h"]
    o = pahli_kare(c, kw + 2 * d, P["pah"]); i_ = pahli_kare(c, kw - 0.1, P["pah"]); n = len(o)
    z0, z1 = zk - h, zk + 0.03
    ob, ot = [g.V(q, z0) for q in o], [g.V(q, z1) for q in o]; ib, it = [g.V(q, z0) for q in i_], [g.V(q, z1) for q in i_]
    for k in range(n):
        j = (k + 1) % n
        g.F([ob[k], ob[j], ot[j], ot[k]], M["tugla"]); g.F([ib[j], ib[k], it[k], it[j]], M["tugla"])
        g.F([ot[k], ot[j], it[j], it[k]], M["tugla"]); g.F([ob[j], ob[k], ib[k], ib[j]], M["tugla"])
