def etekli_kubbe(g, c, kw, zk, zt, kd, segs=24, rings=8):
    """v05: dışa açılan kurşun etekli kubbe, tek kapalı dönel hacim. Etek dudağı kasnak köşesinin D_etek_tasma dışında,
    kasnak üstünden (zk) başlar; içbükey eğriyle kubbe tabanına (kd/2, zf) yükselir; üstte basık küre parçası (tepe zt)."""
    Re = kw / 2 / math.cos(math.pi / 8) + P["D_etek_tasma"]; a = kd / 2
    zf = zk + P["D_etek_oran"] * (zt - zk); rise = zt - zf; dk = P["D_etek_kalinlik"]
    prof = [(0.0, zk), (Re, zk), (Re, zk + dk)]
    for k in range(1, 6):                                     # etek: içbükey (kenarda yatık, kubbeye doğru dikleşir)
        t = k / 5; prof.append((Re - (Re - a) * t, zk + dk + (zf - zk - dk) * t * t))
    Rs = (a * a + rise * rise) / (2 * rise); am = math.atan2(a, Rs - rise)
    for k in range(1, rings):
        al = am * (rings - k) / rings; prof.append((Rs * math.sin(al), zf + Rs * (math.cos(al) - math.cos(am))))
    prof.append((0.0, zt))
    g.lathe(c, prof, segs, [M["kubbe"]] * (len(prof) - 1))
    return (c, zk, zt - zk)
