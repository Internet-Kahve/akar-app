    h = max(za - zs, 0.05); R = (h * h + w * w / 4) / w; cx = w / 2 - R; tm = math.atan2(h, -cx)
    sag = [(cx + R * math.cos(tm * k / n), zs + R * math.sin(tm * k / n)) for k in range(1, n + 1)]
    sag[-1] = (0.0, za)
    sol = [(-s, z) for s, z in reversed(sag[:-1])]
    return [(-w / 2, z0), (w / 2, z0), (w / 2, zs)] + sag + sol + [(-w / 2, zs)]
