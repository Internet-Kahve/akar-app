def katmanli_prism(g, poly, levels, mat_fn, ek=(), ust_m=None, alt_m=None):
    """v06: kapalı dik prizma. Yan yüzler `levels` kotlarında yatay şeritlere, kenarlar `ek` noktalarında düşey parçalara bölünür;
    her parçanın malzemesini mat_fn(merkez_xy, z0, z1, dış_normal_xy) verir (Boolean EXACT sonrası malzeme kaynak yüzden gelir)."""
    p = A.ccw(poly); pts = []
    for i in range(len(p)):
        a, b_ = p[i], p[(i + 1) % len(p)]; pts.append(a); d = b_ - a; L = d.length
        ins = sorted(((q - a).dot(d) / L, q) for q in ek if abs((q - a).x * d.y - (q - a).y * d.x) < 1e-4 * L and 1e-4 < (q - a).dot(d) / L < L - 1e-4)
        pts += [q for _, q in ins]
    V = [[g.V(q, z) for q in pts] for z in levels]; n = len(pts)
    for r in range(len(levels) - 1):
        for i in range(n):
            j = (i + 1) % n; e = pts[j] - pts[i]; nn = Vector((e.y, -e.x)).normalized(); c = (pts[i] + pts[j]) / 2
            g.F([V[r][i], V[r][j], V[r + 1][j], V[r + 1][i]], mat_fn(c, levels[r], levels[r + 1], nn))
    g.F(V[-1], ust_m or mat_fn(None, levels[-1], levels[-1], Vector((0, 0)))); g.F(V[0][::-1], alt_m or mat_fn(None, levels[0], levels[0], Vector((0, 0))))


